-- ---------------------------------------------------------------------------
-- V7  Test results: one result per ordered test, one value per parameter,
--     plus an append-only amendment history.
-- ---------------------------------------------------------------------------

CREATE TABLE test_result (
    id                 BIGINT       NOT NULL AUTO_INCREMENT,
    sample_item_id     BIGINT       NOT NULL,
    sample_id          BIGINT       NOT NULL,
    lab_order_id       BIGINT       NOT NULL,
    patient_id         BIGINT       NOT NULL,
    lab_test_id        BIGINT       NOT NULL,
    test_code          VARCHAR(32)  NOT NULL,
    test_name          VARCHAR(160) NOT NULL,
    department_id      BIGINT       NOT NULL,
    department_name    VARCHAR(120) NOT NULL,
    status             VARCHAR(24)  NOT NULL,
    comment            VARCHAR(2000) NULL,
    has_abnormal       TINYINT(1)   NOT NULL DEFAULT 0,
    has_critical       TINYINT(1)   NOT NULL DEFAULT 0,
    entered_at         DATETIME(6)  NULL,
    entered_by         VARCHAR(100) NULL,
    verified_at        DATETIME(6)  NULL,
    verified_by        VARCHAR(100) NULL,
    approved_at        DATETIME(6)  NULL,
    approved_by        VARCHAR(100) NULL,
    amended_at         DATETIME(6)  NULL,
    amended_by         VARCHAR(100) NULL,
    rejection_reason   VARCHAR(500) NULL,
    version            BIGINT       NOT NULL DEFAULT 0,
    created_at         DATETIME(6)  NOT NULL,
    updated_at         DATETIME(6)  NOT NULL,
    created_by         VARCHAR(100) NULL,
    updated_by         VARCHAR(100) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_test_result_sample_item UNIQUE (sample_item_id),
    CONSTRAINT fk_test_result_sample_item FOREIGN KEY (sample_item_id) REFERENCES sample_item (id) ON DELETE CASCADE,
    CONSTRAINT fk_test_result_sample      FOREIGN KEY (sample_id)      REFERENCES sample (id),
    CONSTRAINT fk_test_result_order       FOREIGN KEY (lab_order_id)   REFERENCES lab_order (id),
    CONSTRAINT fk_test_result_patient     FOREIGN KEY (patient_id)     REFERENCES patient (id),
    CONSTRAINT fk_test_result_test        FOREIGN KEY (lab_test_id)    REFERENCES lab_test (id),
    INDEX ix_test_result_status (status),
    INDEX ix_test_result_department (department_id, status),
    INDEX ix_test_result_sample (sample_id),
    INDEX ix_test_result_order (lab_order_id),
    INDEX ix_test_result_patient (patient_id)
) ENGINE = InnoDB;

CREATE TABLE result_value (
    id                  BIGINT        NOT NULL AUTO_INCREMENT,
    test_result_id      BIGINT        NOT NULL,
    test_parameter_id   BIGINT        NOT NULL,
    parameter_name      VARCHAR(160)  NOT NULL,
    parameter_unit      VARCHAR(32)   NULL,
    data_type           VARCHAR(32)   NOT NULL,
    display_order       INT           NOT NULL DEFAULT 0,
    value_numeric       DECIMAL(16,4) NULL,
    value_text          VARCHAR(500)  NULL,
    flag                VARCHAR(16)   NOT NULL DEFAULT 'NONE',
    reference_text      VARCHAR(160)  NULL,
    version             BIGINT        NOT NULL DEFAULT 0,
    created_at          DATETIME(6)   NOT NULL,
    updated_at          DATETIME(6)   NOT NULL,
    created_by          VARCHAR(100)  NULL,
    updated_by          VARCHAR(100)  NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_result_value_result    FOREIGN KEY (test_result_id) REFERENCES test_result (id) ON DELETE CASCADE,
    CONSTRAINT fk_result_value_parameter FOREIGN KEY (test_parameter_id) REFERENCES test_parameter (id),
    INDEX ix_result_value_result (test_result_id, display_order)
) ENGINE = InnoDB;

CREATE TABLE result_value_history (
    id                BIGINT       NOT NULL AUTO_INCREMENT,
    test_result_id    BIGINT       NOT NULL,
    parameter_name    VARCHAR(160) NOT NULL,
    old_value         VARCHAR(500) NULL,
    new_value         VARCHAR(500) NULL,
    reason            VARCHAR(500) NULL,
    changed_by        VARCHAR(100) NOT NULL,
    changed_at        DATETIME(6)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_result_history_result FOREIGN KEY (test_result_id) REFERENCES test_result (id) ON DELETE CASCADE,
    INDEX ix_result_history_result (test_result_id, changed_at)
) ENGINE = InnoDB;
