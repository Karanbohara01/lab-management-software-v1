    private static final int MIN_YEAR = BS_YEAR_ZERO;
    private static final int MAX_YEAR = BS_YEAR_ZERO + DAYS_IN_MONTH.length - 1;

    private BikramSambatCalendar() {
    }

    /**
     * Converts a Gregorian date to Bikram Sambat.
     *
     * @throws IllegalArgumentException if the date falls before the BS 1970 epoch (1913-04-13)
     *                                   or past the end of the lookup table (BS 2090 ≈ AD 2034);
     *                                   never silently returns a wrong result outside that range.
     */
    public static BsDate toBs(LocalDate adDate) {
        if (adDate.isBefore(EPOCH)) {
            throw new IllegalArgumentException(
                    "Date " + adDate + " is before the supported BS epoch (" + EPOCH + " = BS 1970-01-01)");
        }
        long daysSinceEpoch = java.time.temporal.ChronoUnit.DAYS.between(EPOCH, adDate);
        int year = BS_YEAR_ZERO;
        long remaining = daysSinceEpoch;
        while (true) {
            int[] months = monthsFor(year);
            int yearTotal = 0;
            for (int len : months) {
                yearTotal += len;
            }
            if (remaining < yearTotal) {
                for (int m = 0; m < 12; m++) {
                    if (remaining < months[m]) {
                        return new BsDate(year, m + 1, (int) remaining + 1);
                    }
                    remaining -= months[m];
                }
                throw new IllegalStateException("unreachable");
            }
            remaining -= yearTotal;
            year++;
        }
    }

    private static int[] monthsFor(int year) {
        if (year < MIN_YEAR || year > MAX_YEAR) {
            throw new IllegalArgumentException(
                    "BS year " + year + " is outside the supported range " + MIN_YEAR + "-" + MAX_YEAR);
        }
        return DAYS_IN_MONTH[year - BS_YEAR_ZERO];
    }
